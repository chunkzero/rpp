use serde::{Deserialize, Serialize};
use std::path::PathBuf;
use std::time::Duration;

/// Fingerprint for cache invalidation.
/// Uses mtime + size for fast check, hash for content verification.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Fingerprint {
    pub mtime: u64,
    pub size: u64,
    pub hash: u64, // xxhash3_64
}

/// A file entry discovered during the discovery phase.
#[derive(Debug, Clone)]
pub struct FileEntry {
    /// Absolute path to source file
    pub source_path: PathBuf,
    /// Path relative to source root (used for output)
    pub relative_path: PathBuf,
    /// Fingerprint for caching
    pub fingerprint: Fingerprint,
    /// File content (loaded lazily or eagerly based on cache status)
    pub content: Vec<u8>,
}

/// Index of files discovered during discovery phase.
#[derive(Debug, Default)]
pub struct FileIndex {
    /// Files that need processing (changed or new)
    pub entries: Vec<FileEntry>,
    /// Files that can be copied from cache (unchanged)
    pub cached: Vec<CachedEntry>,
}

/// Reference to a cached file that doesn't need reprocessing.
#[derive(Debug, Clone)]
pub struct CachedEntry {
    pub source_path: PathBuf,
    pub output_path: PathBuf,
    /// Cached processed content (stored to avoid reprocessing)
    pub content: Vec<u8>,
}

/// Record of a transformation applied by a processor.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Transformation {
    /// Processor name
    pub processor: String,
    /// Processor version at time of transformation
    pub version: String,
    /// xxhash3 of input content
    pub input_hash: u64,
    /// xxhash3 of output content
    pub output_hash: u64,
}

/// A file after processing through the processor chain.
#[derive(Debug, Clone)]
pub struct ProcessedFile {
    /// Original source path
    pub source_path: PathBuf,
    /// Output path (may differ if processor changed it)
    pub output_path: PathBuf,
    /// Processed content
    pub content: Vec<u8>,
    /// Chain of transformations applied
    pub transformations: Vec<Transformation>,
}

/// A file generated by a generator plugin.
#[derive(Debug, Clone)]
pub struct GeneratedFile {
    /// Output path relative to output root
    pub path: PathBuf,
    /// Generated content
    pub content: Vec<u8>,
    /// Generator that created this file
    pub generator: String,
}

/// Result of a complete build operation.
#[derive(Debug, Clone)]
pub struct BuildResult {
    /// Number of files processed through pipeline
    pub files_processed: usize,
    /// Number of files copied from cache
    pub files_cached: usize,
    /// Number of files created by generators
    pub files_generated: usize,
    /// Number of files cancelled by processors
    pub files_cancelled: usize,
    /// Total build duration
    pub duration: Duration,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_fingerprint_equality() {
        let f1 = Fingerprint {
            mtime: 100,
            size: 200,
            hash: 300,
        };
        let f2 = Fingerprint {
            mtime: 100,
            size: 200,
            hash: 300,
        };
        let f3 = Fingerprint {
            mtime: 100,
            size: 200,
            hash: 301,
        };
        assert_eq!(f1, f2);
        assert_ne!(f1, f3);
    }
}
